/**
 * Copies the glentenorio.com sidebar into the portal, so the portal sits in
 * Glen's site layout and stays in step with it. Source: the portfolio's
 * tools/index.html. Output: src/assets/gt-sidebar.html (committed, so a build
 * without the portfolio next to it still works).
 *
 *   node scripts/sync-gt-sidebar.mjs [path/to/portfolio]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { homedir } from 'node:os';

const root = process.argv[2] || process.env.PORTFOLIO || resolve(homedir(), 'Desktop/Claude Projects/portfolio');
const html = readFileSync(resolve(root, 'tools/index.html'), 'utf8');
const start = html.indexOf('<aside class="side" id="drawer">');
const end = html.indexOf('</aside>', start);
if (start < 0 || end < 0) throw new Error('Sidebar <aside class="side" id="drawer"> not found in tools/index.html');
let inner = html.slice(html.indexOf('>', start) + 1, end);

inner = inner
  .replace(/<!--[\s\S]*?-->/g, '')
  // The portal is hosted on glentenorio.com, so site links stay root-relative.
  // It lives under Tools.
  .replace(/<a href="\/tools\/"(?![^>]*class=)/, '<a href="/tools/" class="active" aria-current="page"')
  .replace(/\n\s*\n/g, '\n')
  .trim();

const out = resolve(import.meta.dirname, '..', 'src/assets/gt-sidebar.html');
writeFileSync(out, `<!-- Generated by scripts/sync-gt-sidebar.mjs from glentenorio.com's tools/index.html. Don't edit by hand. -->\n${inner}\n`);
console.log(`Wrote ${out}`);
